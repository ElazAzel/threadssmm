test('production local build has no credentials, cloud API calls or fake data', async ({ page }) => {
  const calls: string[] = []
  const errors: string[] = []
  page.on('request', request => { if (request.url().includes('/api/') || !request.url().startsWith('http://127.0.0.1:4174')) calls.push(request.url()) })
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/')
  await expect(page).toHaveURL(/\/assistant$/)
  await expect(page.getByRole('heading', { name: 'Ваш редактор Threads' })).toBeVisible()
  await expect(page.getByRole('heading', { name: 'Пока нет источников' })).toBeVisible()
  await importFixture(page)
  await page.reload()
  await expect(page.getByText('@alice', { exact: true })).toBeVisible()
  await expect(page.getByText('@bob', { exact: true })).toBeVisible()
  await importFixture(page)
  await expect(page.getByRole('status')).toContainText('Добавлено: 0. Повторов: 2.')
  await page.getByRole('button', { name: 'Темы и редактор', exact: true }).click()
  await expect(page.getByRole('button', { name: /автоматизация.*2 постов/ })).toBeVisible()
  expect(calls).toEqual([])
  expect(errors).toEqual([])
})

test('single source reply saves, requires review and never silently publishes', async ({ page }) => {
  await page.goto('/assistant')
  await importFixture(page)
  await page.getByRole('button', { name: 'Подготовить ответ' }).first().click()
  await page.getByRole('button', { name: 'Подготовить шаблон' }).click()
  await expect(page.getByRole('heading', { name: 'Черновики и ответы' })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Текст проверен' })).toBeDisabled()
  const text = 'Как вы выбираете задачу для первого эксперимента? Я бы начал с критерия проверки результата.'
  await page.getByLabel('Текст черновика').fill(text)
  await page.getByRole('button', { name: 'Текст проверен' }).click()
  const intent = page.getByRole('link', { name: 'Открыть ответ в Threads' })
  const url = new URL((await intent.getAttribute('href'))!)
  expect(url.origin).toBe('https://www.threads.com')
  expect(url.searchParams.get('text')).toBe(text)
  expect(url.searchParams.get('reply_post_shortcode')).toBe('abc123')
  await page.reload()
  await page.getByRole('button', { name: 'Черновики', exact: true }).click()
  await expect(page.getByLabel('Текст черновика')).toHaveValue(text)
  await expect(page.getByText('Проверен', { exact: true })).toBeVisible()
  await page.getByLabel('Текст черновика').fill('а'.repeat(501))
  await expect(page.getByRole('button', { name: 'Текст проверен' })).toBeDisabled()
  await expect(intent).toHaveCount(0)
  await page.reload()
  await page.getByRole('button', { name: 'Черновики', exact: true }).click()
  await expect(page.getByLabel('Текст черновика')).toHaveValue('а'.repeat(501))
  await expect(page.getByText('Опубликован вручную', { exact: true })).toHaveCount(0)
})

test('backup restores edited drafts, removed sources and profile', async ({ page }) => {
  await page.goto('/assistant')
  await importFixture(page)
  await page.getByRole('button', { name: 'Подготовить ответ' }).first().click()
  await page.getByRole('button', { name: 'Подготовить шаблон' }).click()
  await page.getByLabel('Текст черновика').fill('Обсудим способ проверки результата?')
  await page.getByRole('button', { name: 'Источники', exact: true }).click()
  await page.getByRole('button', { name: 'Убрать из выборки' }).first().click()
  await page.getByRole('button', { name: 'Голос и данные', exact: true }).click()
  await page.getByLabel('Имя / бренд').fill('Мой бренд')
  const downloadEvent = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Скачать резервную копию' }).click()
  const download = await downloadEvent
  const path = await download.path()
  expect(path).toBeTruthy()
  await page.getByRole('button', { name: 'Удалить локальные данные', exact: true }).click()
  await page.keyboard.press('Escape')
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await page.getByRole('button', { name: 'Удалить локальные данные', exact: true }).click()
  await page.getByRole('button', { name: 'Удалить все локальные данные' }).click()
  await page.getByLabel('Восстановить копию').setInputFiles(path!)
  await page.getByRole('button', { name: 'Заменить данные' }).click()
  await expect(page.getByLabel('Имя / бренд')).toHaveValue('Мой бренд')
  await page.reload()
  await page.getByRole('button', { name: 'Черновики', exact: true }).click()
  await expect(page.getByLabel('Текст черновика')).toHaveValue('Обсудим способ проверки результата?')
  await expect(page.getByText('Без ссылки на исходный пост ответ можно только скопировать.')).toBeVisible()
})

