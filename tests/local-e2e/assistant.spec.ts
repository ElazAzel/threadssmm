test('pending model generation cannot restore erased data or cross workspace changes', async ({ page }) => {
  let started = false
  let release: (() => void) | undefined
  const gate = new Promise<void>(resolve => { release = resolve })
  await page.route('**/local/health', route => route.fulfill({ json: { available: true, models: ['test-model'] } }))
  await page.route('**/local/generate', async route => { started = true; await gate; await route.fulfill({ json: { text: JSON.stringify({ parts: ['Этот старый ответ не должен сохраниться.'] }) } }).catch(() => {}) })
  await page.goto('/assistant')
  await importFixture(page)
  await page.getByRole('button', { name: 'Темы и редактор', exact: true }).click()
  await page.getByText('Генерация своей локальной моделью', { exact: true }).click()
  await page.getByRole('button', { name: 'Проверить Ollama' }).click()
  await page.getByRole('button', { name: 'Написать локальной моделью' }).click()
  await expect.poll(() => started).toBe(true)
  await page.getByRole('button', { name: 'Голос и данные', exact: true }).click()
  await page.getByRole('button', { name: 'Удалить локальные данные', exact: true }).click()
  await page.getByRole('button', { name: 'Удалить все локальные данные' }).click()
  release?.()
  await page.getByRole('button', { name: 'Черновики', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Черновиков пока нет' })).toBeVisible()
  expect(await page.evaluate(() => localStorage.getItem('threads-local-workspace-v1'))).toBeNull()
})

test('cross-tab edits revoke pending publication confirmation and preserve newest data', async ({ page, context }) => {
  await page.goto('/assistant')
  await page.getByRole('button', { name: 'Черновики', exact: true }).click()
  await page.getByRole('button', { name: 'Новый пустой черновик' }).click()
  await page.getByLabel('Текст черновика').fill('Первый вариант.')
  await page.getByRole('button', { name: 'Текст проверен' }).click()
  await page.getByRole('button', { name: 'Указать ссылку после публикации' }).click()
  const other = await context.newPage()
  await other.goto('/assistant')
  await other.getByRole('button', { name: 'Черновики', exact: true }).click()
  await other.getByLabel('Текст черновика').fill('Новый вариант из второй вкладки.')
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await expect(page.getByLabel('Текст черновика')).toHaveValue('Новый вариант из второй вкладки.')
  await expect(page.getByText('Черновик', { exact: true })).toBeVisible()
  await page.reload()
  await page.getByRole('button', { name: 'Черновики', exact: true }).click()
  await expect(page.getByLabel('Текст черновика')).toHaveValue('Новый вариант из второй вкладки.')
})

